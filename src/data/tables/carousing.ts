/**
 * Extended carousing tables from the Player's Guide to the Western Reaches
 * (pg. 236-245) — an expansion to the base Shadowdark carousing rules.
 * Each participant rolls 1d8 + their tier's bonus on the Outcome table,
 * which sets how many times they roll the d100 Benefit and Mishap tables
 * (and at what modifier), plus their XP for the night.
 *
 * The Benefit/Mishap flavor text names mechanics this codebase doesn't model
 * (renown, allies, bastions, temporary stat bonuses) — those effects are
 * narrative only here, same as the percentage wealth-loss lines already were
 * in the base carousing table.
 */

import type { RollableTable, TableEntry } from "../../engine";

export interface CarouseOutcomeData {
  mishapRolls: number;
  benefitRolls: number;
  modifier: number;
  xp: number;
}

function outcomeEntry(total: number, data: CarouseOutcomeData): TableEntry {
  return { min: total, max: total, text: `Total ${total}`, data: data as unknown as Record<string, unknown> };
}

