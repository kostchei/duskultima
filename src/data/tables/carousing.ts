function d100Table(id: string, name: string, lines: readonly string[]): RollableTable {
  if (lines.length !== 100) throw new Error(`${id} must define exactly 100 entries, got ${lines.length}`);
  return {
    id,
    name,
    dice: "1d100",
    entries: lines.map((text, i) => ({ min: i + 1, max: i + 1, text })),
  };
}

